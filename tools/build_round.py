"""
Build a round data file (data/round-N.js) from the official MCC allotment PDF.

    py tools/build_round.py ^
        --pdf "C:\\path\\round1.pdf" ^
        --id round-1 --label "Round 1" ^
        --released 2026-10-24 ^
        --source-url "https://cdnbbsr.s3waas.gov.in/...pdf"

The scores file (data/scores.js) is created once from the NBE result PDF:

    py tools/build_round.py --scores-pdf "NEET-PG 2026 Published Result_DS.pdf"
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from bisect import bisect_right
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from parse_allotment import parse_pdf  # noqa: E402
from parse_scores import build_runs, parse_scores  # noqa: E402
from states import resolve_state  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SCORES_JS = ROOT / "data" / "scores.js"
SCORES_CACHE = Path(__file__).parent / ".cache" / "scores_runs.json"


def load_runs(path: Path):
    text = path.read_text(encoding="utf-8")
    match = re.search(r"window\.NEETPG_SCORE_RUNS\s*=\s*(\[.*?\]);", text, re.S)
    if not match:
        raise SystemExit(f"Could not find NEETPG_SCORE_RUNS in {path}")
    runs = json.loads(match.group(1))
    starts = [r[0] for r in runs]
    return runs, starts


def make_score_lookup(runs, starts):
    def lookup(rank: int):
        if rank < starts[0]:
            return None
        idx = bisect_right(starts, rank) - 1
        return runs[idx][1]

    return lookup


class Dict:
    def __init__(self):
        self.values: list[str] = []
        self.index: dict[str, int] = {}

    def add(self, value: str) -> int:
        idx = self.index.get(value)
        if idx is None:
            idx = len(self.values)
            self.values.append(value)
            self.index[value] = idx
        return idx


def build_round(rows, round_id, label, released, source_url):
    if SCORES_JS.exists():
        runs, starts = load_runs(SCORES_JS)
        score_of = make_score_lookup(runs, starts)
    else:
        score_of = lambda rank: None  # noqa: E731

    quota, course, allotted, candidate, remarks = Dict(), Dict(), Dict(), Dict(), Dict()
    institute_index: dict[str, int] = {}
    institutes: list[str] = []
    institute_state: list[str] = []

    out_rows = []
    missing_score = 0

    for row in rows:
        name = row["institute"]
        idx = institute_index.get(name)
        if idx is None:
            idx = len(institutes)
            institutes.append(name)
            institute_state.append(resolve_state(name))
            institute_index[name] = idx

        score = row.get("score")
        if score is None:
            score = score_of(row["rank"])
            if score is None:
                missing_score += 1

        out_rows.append([
            row["rank"],
            score if score is not None else "",
            quota.add(row["quota"]),
            idx,
            course.add(row["course"]),
            allotted.add(row["allottedCategory"]),
            candidate.add(row["candidateCategory"]),
            remarks.add(row["remarks"]),
        ])

    payload = {
        "format": 2,
        "id": round_id,
        "label": label,
        "released": released,
        "sourceUrl": source_url,
        "institutes": institutes,
        "states": institute_state,
        "dict": {
            "quota": quota.values,
            "course": course.values,
            "allotted": allotted.values,
            "candidate": candidate.values,
            "remarks": remarks.values,
        },
        "rows": out_rows,
    }

    stats = {
        "rows": len(out_rows),
        "institutes": len(institutes),
        "courses": len(course.values),
        "quotas": len(quota.values),
        "allotted categories": len(allotted.values),
        "candidate categories": len(candidate.values),
        "missing scores": missing_score,
        "states": sorted(set(institute_state)),
    }
    return payload, stats


def write_round_js(payload, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        f"// {payload['label']} — NEET PG 2026 seat allotment (generated by tools/build_round.py)\n"
        f"// Source: {payload.get('sourceUrl') or 'MCC'}\n"
    )
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    path.write_text(f"{header}window.registerRound({body});\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", help="MCC allotment PDF for this round")
    ap.add_argument("--id", help="e.g. round-1")
    ap.add_argument("--label", help='e.g. "Round 1"')
    ap.add_argument("--released", default="", help="YYYY-MM-DD")
    ap.add_argument("--source-url", default="")
    ap.add_argument("--out", help="output file (default data/<id>.js)")
    ap.add_argument("--scores-pdf", help="NBE result PDF, used once to build data/scores.js")
    ap.add_argument("--rows-json", help="reuse an already parsed rows json instead of the PDF")
    args = ap.parse_args()

    if args.scores_pdf:
        print("Parsing NBE result PDF…")
        pairs = parse_scores(Path(args.scores_pdf))
        runs, unique_ranks, violations = build_runs(pairs)
        print(f"  {len(pairs)} candidates · {unique_ranks} ranks · {len(runs)} score runs · {violations} violations")
        SCORES_CACHE.parent.mkdir(parents=True, exist_ok=True)
        SCORES_CACHE.write_text(json.dumps(runs), encoding="utf-8")
        SCORES_JS.parent.mkdir(parents=True, exist_ok=True)
        SCORES_JS.write_text(
            "// NEET-PG 2026 rank -> score runs: [firstRank, score] pairs. Score is constant\n"
            "// from that rank until the next entry. Generated from the official NBE result PDF.\n"
            f"window.NEETPG_SCORE_RUNS={json.dumps(runs, separators=(',', ':'))};\n",
            encoding="utf-8",
        )
        print(f"  wrote {SCORES_JS.relative_to(ROOT)}")
        if not args.pdf:
            return

    if not args.pdf and not args.rows_json:
        raise SystemExit("Nothing to do: pass --pdf (and --id/--label) or --scores-pdf")
    if not args.id or not args.label:
        raise SystemExit("--id and --label are required when building a round")

    if args.rows_json:
        rows = json.loads(Path(args.rows_json).read_text(encoding="utf-8"))
        print(f"Loaded {len(rows)} rows from {args.rows_json}")
    else:
        print(f"Parsing {args.pdf} …")
        rows = parse_pdf(Path(args.pdf), progress=lambda msg: print(msg, flush=True))
        print(f"  {len(rows)} allotment rows")

    payload, stats = build_round(rows, args.id, args.label, args.released, args.source_url)
    out = Path(args.out) if args.out else ROOT / "data" / f"{args.id}.js"
    write_round_js(payload, out)

    size_mb = out.stat().st_size / 1_048_576
    print(f"\nWrote {out} ({size_mb:.2f} MB)")
    for key, value in stats.items():
        print(f"  {key}: {value if not isinstance(value, list) else ', '.join(value)}")


if __name__ == "__main__":
    main()
